function t = task(id, title, level, unit, topic, instructions, starter, hints, forbidden, ...
    sample, prep, compare, tol, border, reference, solution)
t = struct('id', id, 'title', title, 'level', level, 'unit', unit, 'topic', topic, ...
    'instructions', {instructions}, 'starter', starter, 'hints', {hints}, ...
    'forbidden', {forbidden}, 'sample', sample, 'prep', prep, 'compare', compare, ...
    'tol', tol, 'border', border, 'reference', reference, 'solution', solution);
end

function s = nl()
s = newline;
end

function t = find1(id)
T = tasks();
idx = find(strcmp({T.id}, char(id)), 1);
if isempty(idx)
    error('ImageLab:invalidParameter', 'Unknown Code Lab task "%s".', char(id));
end
t = T(idx);
end

% =========================================================================
function I = taskInput(t)
% Deterministic input image (the same for every student and every run),
% at most 256 pixels on a side so loops written by students stay fast.
generateSampleImages(false);
[A, map] = imread(sampleImages('path', t.sample));
if ~isempty(map), A = ind2rgb(A, map); end
G = toGray(toDouble(A(:, :, 1:min(3, size(A, 3)))));
s = 256 / max(size(G));
if s < 1, G = min(max(resizeImage(G, round(size(G, 1) * s), round(size(G, 2) * s)), 0), 1); end
G = round(G * 255) / 255;                       % exact 8-bit grey levels
switch t.prep
    case 'gray'
        I = G;
    case 'saltpepper'
        state = rng(7);
        I = addSaltPepperNoise(G, 0.06);
        rng(state);
    case 'binary'
        I = G > 0.5;
    otherwise
        error('ImageLab:internal', 'Unknown task input "%s".', t.prep);
end
end

% =========================================================================
function g = grade(t, ws, I)
expected = t.reference(I);
g = struct('passed', false, 'match', 0, 'message', '', 'checks', {{}}, ...
    'expectedId', '', 'diffId', '', 'mae', [], 'mismatch', []);
if strcmp(t.compare, 'vector')
    g.expectedId = '';
else
    g.expectedId = ilab_store('save', shownImage(expected, t.compare), 'expected');
end

if ~isstruct(ws) || ~isfield(ws, 'out')
    g = fail(g, 'Your code must store its result in a variable called out.', 'out exists', false);
    return
end
g.checks{end+1} = check('out exists', true);
v = ws.out;
if ~(isnumeric(v) || islogical(v)) || ~isreal(v)
    g = fail(g, sprintf('out must be a numeric or logical array, but it is a %s.', class(v)), 'out is numeric', false);
    return
end

if strcmp(t.compare, 'vector')
    v = double(v(:)); e = double(expected(:));
    if numel(v) ~= numel(e)
        g = fail(g, sprintf('out must have %d elements, but it has %d.', numel(e), numel(v)), 'right length', false);
        return
    end
    g.checks{end+1} = check('right length', true);
    err = abs(v - e);
    g.mae = mean(err);
    g.match = 100 * mean(err <= t.tol);
    g.passed = max(err) <= t.tol;
    if g.passed
        g.message = 'Correct - every count matches.';
    else
        [~, k] = max(err);
        g.message = sprintf('Not yet: %.1f%% of the values match. For example out(%d) is %g but should be %g.', ...
            g.match, k, v(k), e(k));
    end
    g.checks{end+1} = check('values match', g.passed);
    return
end

% ---- images
if ~isequal(size(v, 1), size(expected, 1)) || ~isequal(size(v, 2), size(expected, 2)) || size(v, 3) ~= size(expected, 3)
    hint = '';
    if size(v, 3) == 3 && size(expected, 3) == 1
        hint = ' It looks like a colour image - the result should be grayscale.';
    elseif isequal(size(v), size(expected) + 2) || isequal(size(v), size(expected) + [2 2 0])
        hint = ' It is 2 pixels larger - remove the padding before storing out.';
    end
    g = fail(g, sprintf('out is %s but should be %s, the same size as img.%s', ...
        sizeText(v), sizeText(expected), hint), 'same size as img', false);
    return
end
g.checks{end+1} = check('same size as img', true);

warn = '';
if isinteger(v)
    v = double(v) / double(intmax(class(v)));
elseif islogical(v)
    v = double(v);
else
    v = double(v);
    if ~strcmp(t.compare, 'normalized') && max(v(:)) > 1.5
        warn = ' Your values go above 1 - did you work on the 0..255 scale? Divide by 255.';
    end
end
v(~isfinite(v)) = 0;
e = double(expected);
b = t.border;
inner = @(X) X(1 + b:end - b, 1 + b:end - b, :);
switch t.compare
    case 'normalized'
        v = v / max(max(abs(v(:))), eps);
        e = e / max(max(abs(e(:))), eps);
        err = abs(inner(v) - inner(e));
        g.mae = mean(err(:));
        g.match = 100 * mean(err(:) <= 0.02);
        g.passed = g.mae <= t.tol;
    case 'binary'
        if ~islogical(ws.out) && ~all(ismember(unique(v(:)), [0 1]))
            warn = ' out should be a binary image (only 0 and 1, e.g. out = img > level).';
        end
        err = double(inner(v > 0.5) ~= inner(e > 0.5));
        g.mismatch = mean(err(:));
        g.match = 100 * (1 - g.mismatch);
        g.passed = g.mismatch <= t.tol && isempty(warn);
    otherwise
        err = abs(inner(v) - inner(e));
        g.mae = mean(err(:));
        g.match = 100 * mean(err(:) <= 2 / 255);
        g.passed = g.mae <= t.tol;
end
D = zeros(size(e, 1), size(e, 2));
D(1 + b:end - b, 1 + b:end - b) = max(err, [], 3);
g.diffId = ilab_store('save', min(D * 4, 1), 'diff');
g.checks{end+1} = check('pixels match the expected result', g.passed);
if g.passed
    g.message = sprintf('Correct! %.1f%% of the pixels match the expected result.', g.match);
else
    g.message = sprintf(['Not yet: %.1f%% of the pixels match. The difference image shows ' ...
        'where your result differs (bright = large difference).%s'], g.match, warn);
end
end

function g = fail(g, message, name, ok)
g.message = message;
g.checks{end+1} = check(name, ok);
end

function c = check(name, ok)
c = struct('name', name, 'ok', ok);
end

function J = shownImage(E, compare)
if strcmp(compare, 'normalized'), J = E / max(max(E(:)), eps); else, J = E; end
end

