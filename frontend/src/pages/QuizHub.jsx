// Opt in to the leaderboard. Scores are always posted under the signed-in
// student's own name and roll number; name = '' means "do not post".
export function PlayerFields({ name, setName }) {
  const { profile, role } = useApp()
  if (role !== 'student' || !profile) return <p className="small muted">Teacher mode: scores are not posted to the leaderboard.</p>
  return (
    <label className="check">
      <input type="checkbox" checked={!!name} onChange={(e) => setName(e.target.checked ? profile.name : '')} />
      Post my score to the leaderboard as <b>{profile.name}</b>{profile.roll ? ` (${profile.roll})` : ''}
    </label>
  )
}

function QuizSetup({ mode, onStart }) {
  const { call } = useApp()
  const [categories, setCategories] = useState([])
  const [chosen, setChosen] = useState([])
  const [difficulty, setDifficulty] = useState('mixed')
  const [n, setN] = useState(10)
  useEffect(() => {
    call('quizCategories', {}, { quiet: true }).then((c) => c && setCategories(asArray(c)))
  }, [call])
  const toggle = (c) => setChosen((s) => (s.includes(c) ? s.filter((x) => x !== c) : [...s, c]))
  const start = async () => {
    const params = mode === 'kernel' ? { mode: 'kernel', n } : { difficulty, categories: chosen.length ? chosen : 'all', n }
    const qs = await call('quizQuestions', params, { label: 'quiz questions' })
    if (qs) onStart(asArray(qs))
  }
  return (
    <div className="controls">
      {mode !== 'kernel' && (
        <>
          <span className="field-label">Difficulty</span>
          <Segmented value={difficulty} onChange={setDifficulty} options={[{ value: 'mixed', label: 'Mixed' }, { value: 'easy', label: 'Easy' }, { value: 'medium', label: 'Medium' }, { value: 'hard', label: 'Hard' }]} />
          <span className="field-label">Categories (none selected = all)</span>
          <div className="row">
            {categories.map((c) => (
              <button key={c} className={`btn btn-small ${chosen.includes(c) ? 'btn-navy' : ''}`} onClick={() => toggle(c)}>{c}</button>
            ))}
          </div>
        </>
      )}
      <span className="field-label">Questions</span>
      <Segmented value={n} onChange={setN} options={[5, 10, 15].map((v) => ({ value: v, label: String(v) }))} />
      <button className="btn btn-primary" onClick={start}>Start {mode === 'kernel' ? 'Kernel Quiz' : mode === 'classroom' ? 'Classroom session' : 'Rapid Fire Quiz'}</button>
    </div>
  )
}

// Weak-topic quiz (services/quiz.py): categories are weighted by the error rate
function WeakPractice() {
  const { call, refreshProgress, progress } = useApp()
  const [plan, setPlan] = useState(null)
  const [questions, setQuestions] = useState(null)
  const [running, setRunning] = useState(false)
  const [summary, setSummary] = useState(null)
  const [n, setN] = useState(10)
  const answered = progress?.questionsAnswered || 0

  const build = async () => {
    const d = await call('quizQuestions', { mode: 'weak', n }, { label: 'Choosing your weak topics' })
    if (d) {
      setPlan(asArray(d.plan))
      setQuestions(asArray(d.questions))
      setSummary(null)
    }
  }
  const finish = async (results) => {
    setRunning(false)
    const d = await call('quizSubmit', { results, mode: 'Weak-topic practice' }, { label: 'Scoring quiz' })
    if (d) {
      setSummary(d)
      refreshProgress()
    }
    setQuestions(null)
    setPlan(null)
  }

  if (running && questions) {
    return <Card><QuizRunner questions={questions} timePerQuestion={20} onFinish={finish} onQuit={() => setRunning(false)} /></Card>
  }
  if (summary) return <Summary summary={summary.summary} progress={summary.progress} onAgain={() => setSummary(null)} />
  const top = (plan || []).filter((x) => x.questions > 0)
  return (
    <Card title="Weak-topic practice">
      <p className="small">
        MATLAB looks at your accuracy per category ({answered} questions answered so far) and draws more questions from the
        topics you get wrong. Unseen topics are included too. 20 seconds per question — this is practice, so it does not go on the leaderboard.
      </p>
      {answered < 5 && <Note kind="warn">You have answered only {answered} questions. Play a Rapid Fire quiz or two first so the practice can find your weak spots.</Note>}
      {!plan ? (
        <div className="row mt-sm">
          <Segmented value={n} onChange={setN} options={[5, 10, 15].map((v) => ({ value: v, label: `${v} questions` }))} />
          <button className="btn btn-primary" onClick={build}>Build my practice quiz</button>
        </div>
      ) : (
        <>
          <div className="table-scroll mt-sm">
            <table className="data">
              <thead><tr><th>Topic</th><th>Your accuracy</th><th style={{ width: '35%' }}>Focus</th><th>Questions</th></tr></thead>
              <tbody>
                {top.map((c) => (
                  <tr key={c.category}>
                    <td><b>{c.category}</b></td>
                    <td>{c.answered ? `${fmt(c.accuracy, 0)}% of ${c.answered}` : <span className="faint">not tried yet</span>}</td>
                    <td><div className={`progressbar ${c.accuracy != null && c.accuracy < 60 ? 'danger' : c.accuracy != null && c.accuracy < 80 ? 'warn' : ''}`}><div style={{ width: `${Math.round((c.weight / top[0].weight) * 100)}%` }} /></div></td>
                    <td>{c.questions}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <div className="row mt-sm">
            <button className="btn btn-primary" onClick={() => setRunning(true)}>Start practice</button>
            <button className="btn" onClick={build}>Shuffle again</button>
          </div>
        </>
      )}
    </Card>
  )
}

function Summary({ summary, progress, onAgain }) {
  return (
    <Card className="quiz-card">
      <div className="big-score">{summary.score}</div>
      <p style={{ textAlign: 'center' }} className="muted">points</p>
      <div className="row" style={{ justifyContent: 'center', gap: 30, margin: '10px 0 16px' }}>
        <div><b>{summary.correct} / {summary.total}</b> correct</div>
        <div><b>{fmt(summary.accuracy, 1)}%</b> accuracy</div>
        <div><b>{summary.bestStreak}</b> best streak</div>
        {progress && <div>Level <b>{progress.level}</b> · {progress.xp} XP</div>}
      </div>
      {progress && asArray(progress.newBadges).length > 0 && <Note kind="ok">🏅 New badge: <b>{asArray(progress.newBadges).join(', ')}</b></Note>}
      {summary.correct === summary.total && summary.total >= 10 && <Note kind="ok">💯 Perfect quiz!</Note>}
      <div className="row" style={{ justifyContent: 'center', marginTop: 14 }}>
        <button className="btn btn-primary" onClick={onAgain}>Play again</button>
        <a className="btn" href="#leaderboard">Leaderboard</a>
        <a className="btn" href="#dashboard">Dashboard</a>
      </div>
    </Card>
  )
}

function TimedQuiz({ mode }) {
  const { call, refreshProgress, profile } = useApp()
  const [questions, setQuestions] = useState(null)
  const [summary, setSummary] = useState(null)
  const [name, setName] = useState(() => profile?.name || '')
  const [classScore, setClassScore] = useState(null)

  const finish = async (results) => {
    if (mode === 'classroom') {
      const correct = results.filter((r) => r.correct).length
      setClassScore({ correct, total: results.length })
      setQuestions(null)
      return
    }
    const d = await call('quizSubmit', { results, name, mode: mode === 'kernel' ? 'Kernel Quiz' : 'Rapid Fire' }, { label: 'Scoring quiz' })
    if (d) {
      setSummary(d)
      refreshProgress()
    }
    setQuestions(null)
  }

  if (questions) {
    return (
      <Card>
        <QuizRunner questions={questions} timePerQuestion={10} classroom={mode === 'classroom'} onFinish={finish} onQuit={() => setQuestions(null)} />
      </Card>
    )
  }
  if (summary) return <Summary summary={summary.summary} progress={summary.progress} onAgain={() => setSummary(null)} />
  return (
    <Card title={mode === 'kernel' ? 'Kernel Quiz' : mode === 'classroom' ? 'Classroom Mode' : 'Rapid Fire Quiz'}>
      {classScore && <Note kind="ok">Class result of the last session: <b>{classScore.correct} / {classScore.total}</b> answered correctly.</Note>}
      {mode === 'classroom'
        ? <p className="small">Put this on the projector. The question and a 10-second timer are shown in large type. Click the option the class chooses (or let the timer run out / "Reveal answer now"), then discuss the explanation.</p>
        : <PlayerFields name={name} setName={setName} />}
      <div style={{ marginTop: 12 }}>
        <QuizSetup mode={mode} onStart={(qs) => { setClassScore(null); setQuestions(qs) }} />
      </div>
      <p className="small muted" style={{ marginTop: 12 }}>
        Scoring: 100 × difficulty (easy 1, medium 1.5, hard 2) + 5 per second left + 10 × streak bonus.
      </p>
    </Card>
  )
}

const gameFromHash = () => {
  const m = window.location.hash.match(/[?&]game=(\w+)/)
  return m && GAMES.some((g) => g.key === m[1]) ? m[1] : null
}

export default function QuizHub() {
  const [game, setGame] = useState(gameFromHash)
  const current = GAMES.find((g) => g.key === game)
  return (
    <Page title={current ? current.title : 'Arcade'} eyebrow="Play" subtitle={current ? current.text : 'Eight ways to test yourself. Questions, images and scores all come from MATLAB.'}
      back={game ? { label: 'All games', onClick: () => setGame(null) } : null}>
      {!game && (
        <div className="game-tiles">
          {GAMES.map((g) => (
            <button key={g.key} className="game-tile" onClick={() => setGame(g.key)}>
              {g.tag && <span className="badge tag">{g.tag}</span>}
              <span className="ic" aria-hidden="true">{g.icon}</span><b>{g.title}</b><span>{g.text}</span>
            </button>
          ))}
        </div>
      )}
      {(game === 'rapid' || game === 'kernel' || game === 'classroom') && <TimedQuiz key={game} mode={game} />}
      {game === 'guess' && <GuessFilter />}
      {game === 'pipeline' && <PipelineGame />}
      {game === 'challenge' && <ChallengeMode />}
      {game === 'weak' && <WeakPractice />}
      {game === 'daily' && <DailyChallenge />}
    </Page>
  )
}
