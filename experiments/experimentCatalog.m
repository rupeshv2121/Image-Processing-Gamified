     'It reduces random noise because noise values average out, but it also blurs edges, and it does ' ...
     'NOT remove impulse noise - an outlier just spreads into its neighbours.'], ...
    {'Read the image and add Gaussian noise', 'Create the 3x3 averaging kernel ones(3)/9', ...
     'For each pixel extract the 3x3 neighbourhood', 'Compute the average and store it', 'Repeat for k = 5 and 7', 'Compare PSNR/SSIM'}, ...
