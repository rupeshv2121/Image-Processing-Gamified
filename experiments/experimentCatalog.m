function E = add(E, number, title, aim, theory, algorithm, code, manualCode, howItWorks, ...
    observation, conclusion, functions, quizCategory, defaultImage)
E(end+1) = struct('number', number, 'title', title, 'aim', aim, 'theory', theory, ...
    'algorithm', {algorithm}, 'code', code, 'manualCode', manualCode, ...
    'howItWorks', {howItWorks}, 'observation', observation, 'conclusion', conclusion, ...
    'functions', {functions}, 'quizCategory', quizCategory, 'defaultImage', defaultImage);
end
